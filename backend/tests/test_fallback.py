"""
Tests for the Gemini -> Mistral/Groq failover and local URL fallback.
No network or API keys needed: provider calls are mocked.
"""
import asyncio
import unittest
from unittest.mock import patch

from app.core import config, gemini_client, llm_fallback
from app.services import url_fetcher
from app.services.retry import ImmediateFallbackError, RateLimitError


def run(coro):
    return asyncio.run(coro)


class FakeAPIError(Exception):
    def __init__(self, code, message):
        super().__init__(message)
        self.code = code


class TestFallback(unittest.TestCase):
    def test_503_is_treated_as_transient(self):
        exc = FakeAPIError(503, "503 UNAVAILABLE. This model is currently experiencing high demand.")
        with self.assertRaises(RateLimitError):
            gemini_client._raise_if_transient(exc)

    def test_429_is_treated_as_transient(self):
        with self.assertRaises(ImmediateFallbackError):
            gemini_client._raise_if_transient(FakeAPIError(429, "RESOURCE_EXHAUSTED"))

    def test_quota_message_switches_to_fallback_without_retries(self):
        with self.assertRaises(ImmediateFallbackError):
            gemini_client._raise_if_transient(FakeAPIError(None, "You exceeded your current quota"))

    def test_400_is_not_treated_as_transient(self):
        with self.assertRaises(FakeAPIError):
            gemini_client._raise_if_transient(FakeAPIError(400, "INVALID_ARGUMENT bad schema"))

    def test_extract_json_plain(self):
        self.assertEqual(llm_fallback._extract_json('{"a": 1}'), {"a": 1})

    def test_extract_json_code_fence(self):
        self.assertEqual(llm_fallback._extract_json('```json\n{"a": 1}\n```'), {"a": 1})

    def test_extract_json_with_preamble(self):
        self.assertEqual(llm_fallback._extract_json('Sure! Here you go: {"a": 1} Hope that helps'), {"a": 1})

    def test_extract_json_rejects_non_object(self):
        with self.assertRaises(ValueError):
            llm_fallback._extract_json("[1, 2, 3]")

    @patch.object(config, "FALLBACK_ORDER", ["mistral", "groq"])
    @patch.object(config, "MISTRAL_API_KEY", "")
    @patch.object(config, "GROQ_API_KEY", "g-key")
    def test_provider_without_key_is_skipped(self):
        providers = llm_fallback._providers()
        self.assertEqual([p["name"] for p in providers], ["groq"])

    @patch.object(config, "FALLBACK_ORDER", ["mistral", "groq"])
    @patch.object(config, "MISTRAL_API_KEY", "m-key")
    @patch.object(config, "GROQ_API_KEY", "g-key")
    def test_next_provider_used_when_first_fails(self):
        calls = []

        async def fake_call(provider, messages, use_json_mode=True):
            calls.append(provider["name"])
            if provider["name"] == "mistral":
                raise llm_fallback.FallbackError("mistral HTTP 503")
            return '{"hook": "hi"}'

        with patch.object(llm_fallback, "_call_provider", fake_call):
            result = run(llm_fallback.generate_json("sys", "src", {"required": ["hook"]}))
            self.assertEqual(result, {"hook": "hi"})
            self.assertEqual(calls, ["mistral", "groq"])

    @patch.object(config, "FALLBACK_ORDER", ["mistral", "groq"])
    @patch.object(config, "MISTRAL_API_KEY", "m-key")
    @patch.object(config, "GROQ_API_KEY", "g-key")
    def test_malformed_reply_is_retried_once_on_same_provider(self):
        replies = iter(["not json at all", '{"hook": "ok"}'])
        calls = []

        async def fake_call(provider, messages, use_json_mode=True):
            calls.append(provider["name"])
            return next(replies)

        with patch.object(llm_fallback, "_call_provider", fake_call):
            result = run(llm_fallback.generate_json("sys", "src", {"required": ["hook"]}))
            self.assertEqual(result, {"hook": "ok"})

    @patch.object(config, "FALLBACK_ORDER", ["groq"])
    @patch.object(config, "GROQ_API_KEY", "g-key")
    def test_groq_is_used_before_gemini(self):
        calls = []

        async def gemini_quota(*args, **kwargs):
            raise ImmediateFallbackError("429 quota exhausted")

        async def groq_response(system_instruction, source_content, schema, **kwargs):
            calls.append((system_instruction, source_content, schema))
            return {"hook": "Generated by Groq"}

        with (
            patch.object(gemini_client, "_gemini_generate", gemini_quota),
            patch.object(llm_fallback, "generate_json", groq_response),
        ):
            result = run(gemini_client.generate("system", "source", {"required": ["hook"]}))

        self.assertEqual(result, {"hook": "Generated by Groq"})
        self.assertEqual(len(calls), 1)

    @patch.object(config, "FALLBACK_ORDER", ["groq"])
    @patch.object(config, "GROQ_API_KEY", "g-key")
    def test_fallback_failure_is_raised_not_simulated(self):
        async def gemini_quota(*args, **kwargs):
            raise ImmediateFallbackError("429 quota exhausted")

        async def groq_failure(*args, **kwargs):
            raise llm_fallback.FallbackError("Groq HTTP 503")

        with (
            patch.object(gemini_client, "_gemini_generate", gemini_quota),
            patch.object(llm_fallback, "generate_json", groq_failure),
            self.assertRaisesRegex(RuntimeError, "Groq was unavailable and Gemini failed"),
        ):
            run(gemini_client.generate("system", "source", {"required": ["hook"]}))


if __name__ == "__main__":
    unittest.main()
